-- Creates the analyzed_reports table to store all Groq AI & Document analyses.

CREATE TABLE IF NOT EXISTS public.analyzed_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_type TEXT NOT NULL,
  title TEXT NOT NULL,
  batch_id TEXT,
  facility TEXT DEFAULT 'Quadcore - Unit 4',
  model TEXT,
  input_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  analysis_result JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security (backend uses service_role key)
ALTER TABLE public.analyzed_reports ENABLE ROW LEVEL SECURITY;

-- Grant full access to service_role (used by backend & server)
GRANT USAGE ON SCHEMA public TO service_role;
GRANT ALL ON TABLE public.analyzed_reports TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;
